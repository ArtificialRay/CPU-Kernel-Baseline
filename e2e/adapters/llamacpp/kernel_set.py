#!/usr/bin/env python3
"""Compile one author's solutions into shared objects and write the override manifest that
e2e/adapters/llamacpp/override/ loads at runtime.

The input is bench-trace/solutions/<dataset>/<author>/gemm/*.json -- what the MCP server
persisted (and `bench_fleet.py --sync-solutions` pulled back) for each definition the agent
submitted, or a hand-written / reference-scalar set. Each solution carries its own harness
(gemm.h, gemm.cpp) and kernel.cpp, so it is compiled exactly as the harness compiled it:
-O3 + the ISA's -march. The emitted manifest is

  {"framework":"llamacpp", "isa":..., "march":..., "author":...,
   "kernels":[{"op":"mul_mat","type":"q4_K","K":2560,"N":9216,
               "so":".../gemm_ggml_q4_K_n9216_k2560.so",
               "symbol":"armbench_entry_gemm","abi":"entry",
               "embeddable":true, "definition":..., "version":...}],
   "skipped":[{"definition":..., "embeddable":false, "reason":...}, ...]}

The hook reads op/type/K/N/so/symbol/abi/symbol_rows/threads and skips every other key, so the
extra fields here (framework, embeddable, ...) are for the people and tools reading the manifest.

Only definitions named gemm_ggml_<type>_n<N>_k<K> are spliceable (packed ABI); others are
listed under "skipped" with a reason, as is a kernel that calls ggml's own routines.

  python3 -m e2e kernel_set --author claude-code-claude-fable-5-1-sve2 --isa sve2 --out ~/e2e/manifest.json
  python3 -m e2e kernel_set --author reference-scalar --rows-abi --out ~/e2e/refscalar/manifest.json
  --only-types q4_K   (attribution runs: restrict to one quant type)
  --only-roles ffn    (substring match on definition name)
  --only NAME ...     (exact definition names)

Guards, checked after the manifest is built (exit 1 when one fails):
  --expect-count N              the manifest holds exactly N kernels
  --reference-author A2         compare against author A2's solutions for the same definitions
    --expect-changed NAME ...   each of these MUST differ from A2's (a stale set is the failure mode)
    --expect-same NAME ...      each of these MUST be byte-identical (deliberately reused)
  --forbid REGEX ...            no kernel's source may match
Sources are compared as the compiler sees them under the rows ABI, so --rows-abi doesn't matter.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))
from contracts import _isa_table  # noqa: E402  (config/kernel_contracts.yaml isa table)

NAME_RX = re.compile(r"^gemm_ggml_(q[456]_K)_n(\d+)_k(\d+)$")
FRAMEWORK = "llamacpp"
SOLUTIONS = REPO / "bench-trace" / "solutions"
# What the MCP server keeps next to <definition>.json while a session runs
# (agent_tools/base.py); a leftover one is the last compile, not the submitted best.
INTERMEDIATE_SUFFIXES = ("_current", "_best")


RT_GEMM_CPP = """// Binding harness (runtime-N variant, generated by build_manifest.py --rows-abi).
// N lives in a thread_local so the e2e override can hand each ggml thread a row range:
//   armbench_entry_gemm(A, out, B, M)             -> all N_FULL rows (out stride N_FULL)
//   armbench_entry_gemm_rows(A, out, B, M, n_rows) -> rows [0, n_rows) of B, out stride n_rows
#include "gemm.h"
namespace gemm_def { thread_local int N = N_FULL; }
using namespace gemm_def;

extern "C" int armbench_entry_gemm(const uint16_t* A, float* output, const uint8_t* B_blocks, int M)
{
    gemm_def::N = N_FULL;
    inner_gemm(A, output, B_blocks, M);
    return 0;
}
extern "C" int armbench_entry_gemm_rows(const uint16_t* A, float* output, const uint8_t* B_blocks, int M, int n_rows)
{
    gemm_def::N = n_rows;
    inner_gemm(A, output, B_blocks, M);
    return 0;
}
"""


def kernel_rows_abi_text(src: str) -> str:
    """The kernel.cpp rewrite the rows ABI needs: mutable static scratch becomes
    thread_local, because the override hands each ggml thread its own row range
    (const lookup tables are left alone).  Idempotent, so it doubles as the
    normaliser the --expect-* guards compare sources through."""
    src = re.sub(r"\bstatic\s+std::vector", "static thread_local std::vector", src)
    src = re.sub(r"\bstatic\s+(?!const\b|constexpr\b|inline\b|thread_local\b)((?:[A-Za-z_][A-Za-z0-9_:<>]*\s+)+)([A-Za-z_][A-Za-z0-9_]*\s*\[)",
                 r"static thread_local \1\2", src)
    return src


def rows_abi_sources(build: Path, N: int) -> None:
    """Rewrite the materialized harness so N is a runtime thread_local (see RT_GEMM_CPP)
    and make the kernel's static scratch buffers thread-local."""
    h = (build / "gemm.h").read_text()
    old = f"constexpr int N = {N};"
    assert old in h, "gemm.h layout changed; cannot rewrite N"
    h = h.replace(old, f"constexpr int N_FULL = {N};\nextern thread_local int N;   // runtime (rows-abi), == N_FULL unless the override splits rows")
    (build / "gemm.h").write_text(h)
    (build / "gemm.cpp").write_text(RT_GEMM_CPP)
    (build / "kernel.cpp").write_text(kernel_rows_abi_text((build / "kernel.cpp").read_text()))


def undefined_ggml_symbols(so: Path) -> list:
    """ggml symbols the .so expects someone else to provide.

    The evaluation harness links ggml, so a candidate that just calls
    ggml_vec_dot_q5_K_q8_K compiles, runs and scores ~1.00x -- it *is* the baseline. The
    e2e override dlopens the kernel on its own, where that symbol does not resolve, and the
    loader then disables every override in the manifest, not just this one. Catch it here.
    """
    try:
        out = subprocess.run(["nm", "-D", "-u", str(so)], capture_output=True, text=True).stdout
    except FileNotFoundError:
        return []
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if parts and parts[0] in ("U", "w") and len(parts) > 1:
            pass
        for tok in parts:
            if tok.startswith("ggml_"):
                syms.add(tok)
    return sorted(syms)


FLAT_QUANT_RX = re.compile(r"^gemm_(q4_k_m|q5_k|q6_k|q8_0)_n\d+_k\d+$")


def embeddable(name: str) -> tuple[bool, str]:
    """Can the override hook splice a kernel for this definition into llama.cpp, and if
    not, why. Only the packed ggml block-row gemms can be: the hook matches a mul_mat by
    (ggml type, K, N) and hands the kernel the raw block rows."""
    if NAME_RX.match(name):
        return True, ""
    if name.startswith("gemm_ggml_"):
        return False, "packed ggml gemm of a type the hook has no kernel for (q4_K/q5_K/q6_K only)"
    if FLAT_QUANT_RX.match(name):
        return False, "flat-quant ABI (separate quant / scales / mins tensors), not ggml block rows"
    return False, "not a packed-ABI gemm definition"


def load_author(dataset: str, author: str, root: Path = SOLUTIONS) -> dict:
    """definition name -> solution JSON for every `<definition>.json` of one author."""
    sol_dir = root / dataset / author / "gemm"
    if not sol_dir.is_dir():
        raise SystemExit(f"no such solutions dir: {sol_dir}")
    out = {}
    for f in sorted(sol_dir.glob("*.json")):
        if f.stem.endswith(INTERMEDIATE_SUFFIXES):
            continue
        out[f.stem] = json.loads(f.read_text())
    return out


def kernel_text(solution: dict) -> str:
    return next(s["content"] for s in solution["sources"] if s["path"] == "kernel.cpp")


def digest(text: str) -> str:
    """Hash of a kernel source as the compiler sees it under the rows ABI. The rewrite is
    idempotent, so comparing through it works whether or not --rows-abi was used."""
    return hashlib.sha256(kernel_rows_abi_text(text).encode()).hexdigest()[:12]


def compile_so(cxx: str, march: str, build: Path, so: Path):
    cmd = [cxx, "-shared", "-fPIC", "-O3", march, "-std=c++14", "-I", str(build),
           str(build / "kernel.cpp"), str(build / "gemm.cpp"), "-o", str(so)]
    return subprocess.run(cmd, capture_output=True, text=True)


def build_kernels(solutions: dict, args, out_dir: Path, march: str):
    kernels, skipped = [], []
    for name, sol in sorted(solutions.items()):
        ok, why = embeddable(name)
        if not ok:
            skipped.append({"definition": name, "embeddable": False, "reason": why}); continue
        qtype, N, K = (lambda m: (m.group(1), int(m.group(2)), int(m.group(3))))(NAME_RX.match(name))
        if args.only and name not in args.only:
            skipped.append({"definition": name, "reason": "filtered by --only"}); continue
        if args.only_types and qtype not in args.only_types:
            skipped.append({"definition": name, "reason": "filtered by --only-types"}); continue
        if args.only_roles and not any(r in name for r in args.only_roles):
            skipped.append({"definition": name, "reason": "filtered by --only-roles"}); continue
        build = out_dir / "build" / name
        build.mkdir(parents=True, exist_ok=True)

        def materialize():
            for s in sol["sources"]:
                (build / s["path"]).write_text(s["content"])
        materialize()
        so = out_dir / f"{name}.so"
        abi = "entry"
        if args.rows_abi:
            rows_abi_sources(build, N)
            p = compile_so(args.cxx, march, build, so)
            if p.returncode == 0:
                abi = "entry_rows"
            else:
                print(f"  {name}: rows-abi compile failed, falling back to single-thread entry: "
                      f"{p.stderr.strip().splitlines()[-1][:160] if p.stderr.strip() else '?'}")
                materialize()
        if abi == "entry":
            p = compile_so(args.cxx, march, build, so)
            if p.returncode != 0:
                skipped.append({"definition": name, "embeddable": False, "reason": "compile failed: " + p.stderr[-400:]}); continue
        bad = undefined_ggml_symbols(so)
        if bad:
            skipped.append({
                "definition": name, "embeddable": False,
                "reason": ("references ggml internals (" + ", ".join(bad) + "): the kernel "
                           "delegates to ggml's own routine, so it cannot be dlopened outside "
                           "the harness and would disable every override in this manifest"),
            })
            print(f"  {name}: SKIPPED -- calls ggml internals ({', '.join(bad)})")
            continue
        kernels.append({"op": "mul_mat", "type": qtype, "K": K, "N": N, "so": str(so),
                        "symbol": "armbench_entry_gemm", "abi": abi,
                        "embeddable": True, "definition": name, "version": f"solutions/{args.author}"})
        print(f"built {name} abi={abi}")
    return kernels, skipped


def check_guards(args, solutions: dict, kernels: list, reference: dict) -> list:
    """The failures (empty list = all guards hold) for --expect-count / --expect-changed /
    --expect-same / --forbid, judged on the sources that went into the manifest."""
    got = {k["definition"]: kernel_text(solutions[k["definition"]]) for k in kernels}
    fail = []
    if args.expect_count is not None and len(got) != args.expect_count:
        fail.append(f"manifest has {len(got)} kernels, expected {args.expect_count}")
    ref = {name: kernel_text(sol) for name, sol in reference.items()}
    for name in args.expect_changed:
        if name not in got:
            fail.append(f"{name}: expected in the manifest, absent")
        elif name not in ref:
            fail.append(f"{name}: no reference to compare against")
        elif digest(got[name]) == digest(ref[name]):
            fail.append(f"{name}: BYTE-IDENTICAL to the reference -- this is the old kernel, not the new one")
    for name in args.expect_same:
        if name not in got:
            fail.append(f"{name}: expected in the manifest, absent")
        elif name in ref and digest(got[name]) != digest(ref[name]):
            fail.append(f"{name}: expected to be reused unchanged but differs from the reference")
    for pat in args.forbid:
        rx = re.compile(pat)
        for name, text in sorted(got.items()):
            if rx.search(text):
                fail.append(f"{name}: source matches forbidden pattern /{pat}/")
    return fail


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--author", required=True, help="solutions/<dataset>/<AUTHOR>/gemm/*.json to compile")
    ap.add_argument("--dataset", default="llama.cpp")
    ap.add_argument("--solutions-root", type=Path, default=SOLUTIONS)
    ap.add_argument("--isa", default="sve2")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--only-types", nargs="*", default=None)
    ap.add_argument("--only-roles", nargs="*", default=None)
    ap.add_argument("--cxx", default="clang++-18")
    ap.add_argument("--march", default=None,
                    help="override the ISA's -march (e.g. -march=armv8.6-a+i8mm+bf16 to reproduce a "
                         "Graviton run locally on an Apple-silicon Mac)")
    ap.add_argument("--rows-abi", action="store_true",
                    help="recompile each kernel with N as a runtime thread_local and export "
                         "armbench_entry_gemm_rows(A,out,B,M,n_rows) too (manifest abi 'entry_rows'), so the "
                         "override can split rows across ggml's threads; kernels that fail to compile that way "
                         "fall back to the single-thread 'entry' ABI")
    ap.add_argument("--expect-count", type=int, default=None)
    ap.add_argument("--reference-author", default=None)
    ap.add_argument("--expect-changed", nargs="*", default=[])
    ap.add_argument("--expect-same", nargs="*", default=[])
    ap.add_argument("--forbid", nargs="*", default=[])
    args = ap.parse_args()
    out_dir = args.out.parent.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    march = args.march or _isa_table()[args.isa].march

    solutions = load_author(args.dataset, args.author, args.solutions_root)
    kernels, skipped = build_kernels(solutions, args, out_dir, march)
    args.out.write_text(json.dumps(
        {"framework": FRAMEWORK, "isa": args.isa, "march": march, "author": args.author,
         "kernels": kernels, "skipped": skipped}, indent=1))
    print(f"{len(kernels)} kernels, {len(skipped)} skipped -> {args.out}")
    for reason in sorted({s["reason"].split(":")[0] for s in skipped}):
        print(f"  skipped: {reason} ({sum(1 for s in skipped if s['reason'].split(':')[0] == reason)})")

    reference = load_author(args.dataset, args.reference_author, args.solutions_root) if args.reference_author else {}
    fail = check_guards(args, solutions, kernels, reference)
    if fail:
        print("\nFAILED:")
        for f in fail:
            print("  " + f)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
